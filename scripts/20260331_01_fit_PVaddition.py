import numpy as np

# inputs/RE/20250820_02_再エネ導入量_work.xlsx
# PV追加導入量 (エネルギー白書)
x1 = [2014, 2015, 2016, 2017, 2018, 2019, 2020, 2021, 2022, 2023]
y1 = [9.216325, 9.174140762, 6.238407127, 5.439983034, 5.63792882, 5.643492684, 5.750116299, 4.585323166, 4.597138568, 3.097089661]

# IRENA
x2 = [2014, 2015, 2016, 2017, 2018, 2019, 2020, 2021, 2022, 2023, 2024]
y2 = [9.74, 10.811, 7.89, 7.459628, 6.661999, 7.030373, 8.676, 6.545, 4.644, 4.011, 2.533]

a1, b1 = np.polyfit(x1, y1, 1)
print(a1,b1)
a2, b2 = np.polyfit(x2, y2, 1)
print(a2,b2)

x1 = 2014
x2 = 2041

cum1 = 17.66 # GW in 2013
cum2 = 13.599

for i in range(x1, x2):
    tx = i
    ty1 = a1 * tx + b1
    if ty1 < 0:
        ty1 = 0.0
    if i <= 2023:
        cum1 += y1[i-2016]
    else:
        cum1 += ty1

    ty2 = a2 * tx + b2
    if ty2 < 0:
        ty2 = 0.0
    if i <= 2024:
        cum2 += y2[i-2016]
    else:
        cum2 += ty2

    print('%4d %5.3f %7.3f  %5.3f %7.3f ' % (tx,ty1, cum1, ty2, cum2))

